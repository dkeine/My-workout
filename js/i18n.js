function getLang() {
  const stored = localStorage.getItem(LS_LANG);
  if (stored && I18N[stored]) return stored;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return I18N[nav] ? nav : 'en';
}

function setLang(id) {
  if (I18N[id]) localStorage.setItem(LS_LANG, id);
}

function t(key, vars) {
  let s = I18N[getLang()][key] ?? I18N.en[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/* Localized weekday names via Intl — 2024-01-01 is a Monday. */
function dayName(i, style = 'long') {
  const d = new Date(Date.UTC(2024, 0, 1 + i));
  return new Intl.DateTimeFormat(getLang(), { weekday: style, timeZone: 'UTC' }).format(d);
}

function dayShort(i) {
  return dayName(i, 'narrow').toUpperCase();
}

